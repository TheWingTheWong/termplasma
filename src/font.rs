const fn build() -> [[u8; 8]; 96] {
    let mut table = [[0u8; 8]; 96];
    let mut i = 0;
    while i < GLYPHS.len() {
        let (c, art) = GLYPHS[i];
        table[c as usize - 32] = pack(art);
        i += 1;
    }
    table
}

/// Glyph bitmaps for ASCII 32..=127.
static FONT: [[u8; 8]; 96] = build();

/// Whether the font has a real glyph for `c` (after case folding).
pub fn has_glyph(c: char) -> bool {
    let c = c.to_ascii_uppercase();
    c == ' ' || (c.is_ascii() && (' '..='~').contains(&c) && FONT[c as usize - 32] != [0; 8])
}

/// The bitmap for `c`: eight rows, MSB is the leftmost pixel.
pub fn glyph(c: char) -> &'static [u8; 8] {
    let c = c.to_ascii_uppercase();
    if has_glyph(c) { &FONT[c as usize - 32] } else { &FONT[b'?' as usize - 32] }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pack_reads_rows_msb_first() {
        let g = pack("#....... ........ ........ ........ ........ ........ ........ .......#");
        assert_eq!(g[0], 0x80);
        assert_eq!(g[7], 0x01);
    }

    #[test]
    fn letter_shapes() {
        assert_eq!(glyph('T')[0], 0b1111_1100);
        assert_eq!(glyph('T')[1], 0b0011_0000);
        assert_eq!(glyph('a'), glyph('A'), "lowercase folds to uppercase");
        assert_eq!(glyph(' '), &[0; 8]);
    }

    #[test]
    fn full_coverage() {
        for c in ('A'..='Z').chain('0'..='9').chain(" .,!?-:'".chars()) {
            assert!(has_glyph(c), "missing glyph for {c:?}");
        }
        assert!(!has_glyph('~'));
        assert!(!has_glyph('\u{e9}'));
        assert_eq!(glyph('~'), glyph('?'));
    }

    #[test]
    fn glyphs_leave_spacing_column() {
        // Every glyph except '_' and '/' keeps its rightmost column clear so
        // letters never touch.
        for c in (' '..='Z').filter(|&c| has_glyph(c) && c != '/') {
            assert!(glyph(c).iter().all(|row| row & 1 == 0), "glyph {c:?} touches its neighbour");
        }
    }
}
