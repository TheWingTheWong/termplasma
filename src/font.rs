//! An 8x8 bitmap font, authored for the sine scroller.
//!
//! Glyphs are written as ASCII art and packed into bytes by a `const fn`
//! at compile time (one byte per row, most significant bit on the left). A
//! malformed glyph is a compile error, not a runtime surprise. The face is a
//! heavy two-pixel stroke in the style of 80s home-computer ROM fonts, which
//! keeps letters legible after the scroller's vertical displacement.
//!
//! Covers space, digits, A-Z and common punctuation; lowercase is folded to
//! uppercase and anything else renders as `?`.

/// Width and height of every glyph, in pixels.
pub const GLYPH_SIZE: usize = 8;

/// Packs one glyph from 64 `.`/`#` characters (whitespace ignored).
const fn pack(art: &str) -> [u8; 8] {
    let bytes = art.as_bytes();
    let mut rows = [0u8; 8];
    let mut bit = 0;
    let mut i = 0;
    while i < bytes.len() {
        let c = bytes[i];
        i += 1;
        let on = match c {
            b'#' => true,
            b'.' => false,
            b' ' | b'\n' => continue,
            _ => panic!("glyph art may only contain '.', '#' and whitespace"),
        };
        assert!(bit < 64, "glyph art has more than 64 pixels");
        if on {
            rows[bit / 8] |= 0x80 >> (bit % 8);
        }
        bit += 1;
    }
    assert!(bit == 64, "glyph art must have exactly 64 pixels");
    rows
}

